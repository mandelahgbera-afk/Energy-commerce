/** The one place a database error becomes words. Never pass a raw Postgres error onward. */
export const friendly = (name: string, detail?: string): string => {
  const template = errorWords[name];
  if (!template) {
    return 'Something went wrong on our side. Try again, and if it keeps happening tell the owner to look at the books.';
  }
  const withDetail = detail && detail !== '' ? template.replace('{detail}', detail) : template.replace('{detail}', '');
  return withDetail.replace(/\s+\.$/, '.').trim();
};
